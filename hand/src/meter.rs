/// What to answer one held call with.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Verdict {
    Go,						// let it through, uncounted
    Root(PathBuf),			// a root, or a directory holding one: refused with EPERM
    Count(PathBuf, PathBuf),	// a pre-existing file under a mark: (victim, mark)
    Xdev,					// a counted file renamed out of the counted zone: EXDEV, so it is copied and unlinked
}

/// Decides calls against one run's marks.  Kept apart from the kernel so it can be
/// tested without one.
pub struct Judge {
    marks:  Vec<PathBuf>,
    caches: Vec<PathBuf>,		// toolchain caches, free where a mark holds one
    since:  SystemTime,
    zones:  HashSet<PathBuf>,	// `target` directories seen holding CACHEDIR.TAG this run
}

impl Judge {

    pub fn new(marks: Vec<PathBuf>, caches: Vec<PathBuf>, since: SystemTime) -> Self {
        Self { marks, caches, since, zones: HashSet::new() }
    }

    fn mark_of(&self, p: &Path) -> Option<PathBuf> {
        self.marks.iter()
            .filter(|m| p.starts_with(m))
            .max_by_key(|m| m.as_os_str().len())
            .cloned()
    }

    /// Is `p` a root, or a directory with a root inside it?
    fn holds_root(&self, p: &Path) -> bool {
        self.marks.iter().any(|m| m.starts_with(p))
    }

    /// Is `p` inside a cache a tool regenerates?  The mark root itself never is.
    fn regenerable(&mut self, p: &Path, mark: &Path) -> bool {
        let rel = match p.strip_prefix(mark) {
            Ok(r)  => r,
            Err(_) => return false,
        };
        // A toolchain cache the mark HOLDS -- `~/.cache/cargo-targets` in a granted home
        // directory.  Never one that holds the mark: a Diamond's folder kept under
        // `~/.cache/daimond` is the user's work, and is counted like any other (audit F5).
        if self.caches.iter().any(|c| c != mark && c.starts_with(mark) && p.starts_with(c)) {
            return true;
        }
        let mut at = mark.to_path_buf();
        let n = rel.components().count();
        for (i, c) in rel.components().enumerate() {
            // Ancestors only: the entry itself is what is being removed.
            if i + 1 >= n {
                break;
            }
            at.push(c.as_os_str());
            let name = c.as_os_str().to_string_lossy();
            if CACHE_NAMES.contains(&name.as_ref()) {
                return true;
            }
            // Cargo writes the tag into every target directory. Remembered once seen,
            // because `rm -rf target` may take the tag before the rest.
            if name == "target" {
                if self.zones.contains(&at) {
                    return true;
                }
                if at.join("CACHEDIR.TAG").is_file() {
                    self.zones.insert(at.clone());
                    return true;
                }
            }
        }
        false
    }

    fn born_this_turn(&self, p: &Path) -> bool {
        match std::fs::symlink_metadata(p).and_then(|m| m.created()) {
            Ok(t)  => t >= self.since,
            // No birth time, or no file: counted, which is the safe direction.
            Err(_) => false,
        }
    }

    /// An `unlink` or an `rmdir` of `p`.
    pub fn remove(&mut self, p: &Path, is_dir: bool) -> Verdict {
        if self.holds_root(p) {
            return Verdict::Root(p.to_path_buf());
        }
        let mark = match self.mark_of(p) {
            Some(m) => m,
            None    => return Verdict::Go,
        };
        // Nothing there: the kernel answers ENOENT, and git asks this routinely.
        if std::fs::symlink_metadata(p).is_err() {
            return Verdict::Go;
        }
        // An empty directory holds no bytes.
        if is_dir || self.regenerable(p, &mark) || self.born_this_turn(p) {
            return Verdict::Go;
        }
        Verdict::Count(p.to_path_buf(), mark)
    }

    /// A rename of `from` to `to`.
    ///
    /// Two losses hide in a rename.  A counted file moved out of the counted zone is a
    /// removal in disguise, answered [`Verdict::Xdev`].  And a rename onto a file that was
    /// there before the turn destroys that file exactly as an `unlink` would -- `mv -f`,
    /// `sed -i` and every editor's atomic save replace this way -- so the file replaced is
    /// counted, and kept, like one.  Keyed on the source alone, as it was until the audit
    /// of 2026-09-23 (F3), `mv -f <new> <old>` took `<old>` uncounted.
    ///
    /// # Arguments
    /// * `flags` - `renameat2`'s flags, 0 for the other two calls.  An exchange keeps both
    ///   files and a no-replace rename fails rather than replace, so neither loses `to`.
    pub fn rename(&mut self, from: &Path, to: &Path, flags: u64) -> Verdict {
        for p in [from, to] {
            if self.holds_root(p) {
                return Verdict::Root(p.to_path_buf());
            }
        }
        // Nothing to move: the kernel answers ENOENT and nothing at `to` is touched.
        let src = match std::fs::symlink_metadata(from) {
            Ok(m)  => m,
            Err(_) => return Verdict::Go,
        };
        let exchange = flags & RENAME_EXCHANGE != 0;
        // An exchange moves both files, so either may be the one leaving.
        if self.leaves_zone(from, to) || (exchange && self.leaves_zone(to, from)) {
            return Verdict::Xdev;
        }
        if exchange || flags & RENAME_NOREPLACE != 0 || src.is_dir() {
            // A directory replaces only an empty directory, which holds nothing.
            return Verdict::Go;
        }
        self.replaced(to, &src)
    }

    /// Would moving `from` to `to` take a counted file out of the counted zone: into a
    /// cache, which a later `rm -rf` empties for free, or out of the marks altogether?
    fn leaves_zone(&mut self, from: &Path, to: &Path) -> bool {
        let mark = match self.mark_of(from) {
            Some(m) => m,
            None    => return false,
        };
        if std::fs::symlink_metadata(from).is_err()
            || self.regenerable(from, &mark)
            || self.born_this_turn(from)
        {
            return false;
        }
        match self.mark_of(to) {
            Some(to_mark) => self.regenerable(to, &to_mark),
            None          => true,
        }
    }

    /// What replacing `to` with the file `src` describes costs: a counted removal where
    /// `to` is a file that was there before the turn, under a mark and outside a cache.
    fn replaced(&mut self, to: &Path, src: &std::fs::Metadata) -> Verdict {
        let mark = match self.mark_of(to) {
            Some(m) => m,
            None    => return Verdict::Go,
        };
        let old = match std::fs::symlink_metadata(to) {
            Ok(m)  => m,
            Err(_) => return Verdict::Go,	// nothing stands there
        };
        // A directory cannot be replaced by a file, and two names for one inode is a
        // rename the kernel carries out as nothing at all.
        if old.is_dir() || same_inode(&old, src) {
            return Verdict::Go;
        }
        if self.regenerable(to, &mark) || self.born_this_turn(to) {
            return Verdict::Go;
        }
        Verdict::Count(to.to_path_buf(), mark)
    }
}

/// Are these two names for one inode?
#[cfg(unix)]
fn same_inode(a: &std::fs::Metadata, b: &std::fs::Metadata) -> bool {
    use std::os::unix::fs::MetadataExt;
    a.dev() == b.dev() && a.ino() == b.ino()
}

#[cfg(not(unix))]
fn same_inode(_a: &std::fs::Metadata, _b: &std::fs::Metadata) -> bool {
    false
}

/// Where a counted file goes before it is removed: under the turn, then a layer, then its
/// own absolute path.
fn trash_path(trash: &Path, since_ms: u64, layer: u32, victim: &Path) -> PathBuf {
    let mut out = trash.join(fmt!("{}", since_ms)).join(fmt!("{}", layer));
    for c in victim.components() {
        if let Component::Normal(n) = c {
            out.push(n);
        }
    }
    out
}

/// The file in each turn's trash naming the marks its files were taken from, as raw bytes each
/// ended by a NUL, which no path can hold (QA D3).
const MARKS_FILE: &str = "marks0";

/// The same, as WMF4 first wrote it: one UTF-8 mark a line.  Still read, so a turn kept by
/// that build can be put back.
const MARKS_LINES: &str = "marks";

/// Records `mark` as a root the turn `since_ms` took files from, so that a restore writes
/// beneath it and nowhere else (WMF4).  The trash is outside every fence, so no command can
/// add a root here.  The mark is written as its own bytes, so a name that is not UTF-8 or
/// holds a newline or a carriage return goes back as it was (QA D3).
#[cfg(unix)]
fn note_mark(trash: &Path, since_ms: u64, mark: &Path) -> Outcome<()> {
    use std::{
        io::Write,
        os::unix::ffi::OsStrExt,
    };
    // No mark (a file kept from outside every mark): nothing is recorded, and a restore
    // refuses the file rather than put it back somewhere unproven.
    if !mark.is_absolute() {
        return Ok(());
    }
    let turn = trash.join(fmt!("{}", since_ms));
    res!(std::fs::create_dir_all(&turn));
    let file = turn.join(MARKS_FILE);
    let raw = mark.as_os_str().as_bytes();
    if let Ok(held) = std::fs::read(&file) {
        if held.split(|b| *b == 0).any(|m| m == raw) {
            return Ok(());
        }
    }
    let mut rec = raw.to_vec();
    rec.push(0);
    let mut f = res!(std::fs::OpenOptions::new().create(true).append(true).open(&file));
    res!(f.write_all(&rec));
    Ok(())
}

#[cfg(not(unix))]
fn note_mark(_trash: &Path, _since_ms: u64, _mark: &Path) -> Outcome<()> {
    // Nothing recorded: a restore refuses every file, as it does a file kept from no mark.
    Ok(())
}

/// The marks the turn's trash names, each absolute and plain names below the root.
fn marks_noted(turn: &Path) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = Vec::new();
    #[cfg(unix)]
    if let Ok(held) = std::fs::read(turn.join(MARKS_FILE)) {
        use std::os::unix::ffi::OsStrExt;
        out.extend(held.split(|b| *b == 0)
            .filter(|m| !m.is_empty())
            .map(|m| PathBuf::from(std::ffi::OsStr::from_bytes(m))));
    }
    if let Ok(held) = std::fs::read_to_string(turn.join(MARKS_LINES)) {
        out.extend(held.split('\n').filter(|l| !l.is_empty()).map(PathBuf::from));
    }
    out.retain(|m| m.is_absolute()
        && m.components().skip(1).all(|c| matches!(c, Component::Normal(_))));
    out
}

/// The deepest of `marks` holding `p`, or an empty path, which no restore writes beneath.
fn mark_for(marks: &[PathBuf], p: &Path) -> PathBuf {
    marks.iter()
        .filter(|m| p.starts_with(m))
        .max_by_key(|m| m.as_os_str().len())
        .cloned()
        .unwrap_or_default()
}

/// Links `victim` into the trash, or copies it where the link cannot be made.
///
/// An error is a removal refused: what the trash does not hold cannot be put back, and every
/// sentence the hand and the page say about a counted removal says that it can.  The design
/// counted an oversized file twice and let it go uncopied (§4.3); that loses it for good, which
/// is why a file too large to copy is refused instead (audit F6).
fn keep(trash: &Path, since_ms: u64, victim: &Path, mark: &Path) -> Outcome<()> {
    res!(note_mark(trash, since_ms, mark));
    // The same path taken twice in one turn keeps both, a layer apart.
    let mut layer = 0;
    let mut dest = trash_path(trash, since_ms, layer, victim);
    while std::fs::symlink_metadata(&dest).is_ok() {
        layer += 1;
        dest = trash_path(trash, since_ms, layer, victim);
    }
    if let Some(parent) = dest.parent() {
        res!(std::fs::create_dir_all(parent));
    }
    match std::fs::hard_link(victim, &dest) {
        Ok(()) => Ok(()),
        Err(_) => copy_kept(victim, &dest),
    }
}

/// Keeps `victim` at `dest` by copying it, for a file the trash could not link.
fn copy_kept(victim: &Path, dest: &Path) -> Outcome<()> {
    let meta = res!(std::fs::symlink_metadata(victim).map_err(|e| err!(e,
        "it could not be read to be kept"; IO, File)));
    // A link holds a path and is kept as the same path.  Copying THROUGH it would keep whatever
    // it points at, read from wherever that is, and put a file back where a link had been.
    if meta.file_type().is_symlink() {
        return keep_link(victim, dest);
    }
    // A pipe or a socket holds no bytes to keep, and opening one to copy it can wait for ever.
    if !meta.is_file() {
        return Err(err!(
            "it is neither a file nor a link, so the trash cannot hold a copy of it"; Invalid, File));
    }
    if meta.len() > COPY_MAX {
        return Err(err!(
            "it is {} bytes on a different filesystem from the hand's trash, so it could be kept \
            only by copying it, and the hand copies nothing over {} bytes. The user can remove \
            it themselves", meta.len(), COPY_MAX; TooBig, File));
    }
    res!(std::fs::copy(victim, dest).map_err(|e| err!(e,
        "it could not be copied into the hand's trash"; IO, File)));
    Ok(())
}

#[cfg(unix)]
fn keep_link(victim: &Path, dest: &Path) -> Outcome<()> {
    let to = res!(std::fs::read_link(victim).map_err(|e| err!(e,
        "the link could not be read to be kept"; IO, File)));
    res!(std::os::unix::fs::symlink(&to, dest).map_err(|e| err!(e,
        "the link could not be kept in the hand's trash"; IO, File)));
    Ok(())
}

#[cfg(not(unix))]
fn keep_link(_victim: &Path, _dest: &Path) -> Outcome<()> {
    Err(err!("a link cannot be kept on this platform"; Unimplemented, File))
}

