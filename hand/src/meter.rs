/// Installs the notify filter on the calling process and returns the listener's number.
///
/// Called by the launcher after the fence and the deny-list, immediately before `exec`.
/// The context is returned as well and must outlive the `exec`, so that nothing closes
/// the listener before the hand has taken its copy.
#[cfg(target_os = "linux")]
pub fn install() -> Outcome<(libseccomp::ScmpFilterContext, i32)> {
    use libseccomp::{
        ScmpAction,
        ScmpFilterContext,
        ScmpSyscall,
    };
    let mut ctx = res!(ScmpFilterContext::new(ScmpAction::Allow).map_err(|e| err!(
        "The deletion meter's filter could not be created: {}.", e; System, Init)));
    let mut n = 0;
    for name in METERED {
        let sc = match ScmpSyscall::from_name(name) {
            Ok(s)  => s,
            Err(_) => continue, // Absent on this architecture: aarch64 has no `unlink`.
        };
        res!(ctx.add_rule(ScmpAction::Notify, sc).map_err(|e| err!(
            "The deletion meter could not hold {}: {}.", name, e; System, Init)));
        n += 1;
    }
    if n == 0 {
        return Err(err!("The deletion meter found none of the removal calls on this \
            architecture, so it would meter nothing."; System, Unimplemented));
    }
    res!(ctx.load().map_err(|e| err!(
        "The deletion meter's filter could not be installed: {}. It needs Linux 5.5 and \
        libseccomp 2.5.", e; System, Init)));
    let fd = res!(ctx.get_notify_fd().map_err(|e| err!(
        "The deletion meter's filter gave no listener: {}.", e; System, Init)));
    Ok((ctx, fd))
}

/// Takes a copy of the launcher's listener, waiting up to `wait` for it to appear.
///
/// The launcher reports nothing: it has no channel of its own that is not also the
/// command's.  So the hand looks, in `/proc/<pid>/fd`, for the one descriptor that reads
/// as a seccomp listener, and copies it with `pidfd_getfd` -- allowed because the hand is
/// the launcher's parent.
#[cfg(target_os = "linux")]
pub fn grab(pid: u32, wait: Duration) -> Outcome<std::os::fd::OwnedFd> {
    use rustix::process::{
        pidfd_getfd,
        pidfd_open,
        Pid,
        PidfdFlags,
        PidfdGetfdFlags,
    };
    let dir = PathBuf::from(fmt!("/proc/{}/fd", pid));
    let until = std::time::Instant::now() + wait;
    loop {
        // A launcher that has gone, or died, will never install anything.
        let rd = match std::fs::read_dir(&dir) {
            Ok(rd) => rd,
            Err(e) => return Err(err!(
                "The launcher {} ended before it installed the deletion meter ({}).", pid, e;
                System, Missing)),
        };
        let stat = std::fs::read_to_string(fmt!("/proc/{}/stat", pid)).unwrap_or_default();
        let state = stat.rsplit(") ").next().and_then(|s| s.chars().next());
        if matches!(state, Some('Z') | Some('X') | None) {
            return Err(err!(
                "The launcher {} ended before it installed the deletion meter.", pid;
                System, Missing));
        }
        {
            for e in rd.flatten() {
                let is = match std::fs::read_link(e.path()) {
                    Ok(l)  => l.as_os_str() == LISTENER_LINK,
                    Err(_) => false,
                };
                if !is {
                    continue;
                }
                let n: i32 = match e.file_name().to_string_lossy().parse() {
                    Ok(n)  => n,
                    Err(_) => continue,
                };
                let who = res!(Pid::from_raw(pid as i32).ok_or_else(|| err!(
                    "The launcher's process id {} is not one.", pid; Bug, Invalid)));
                let pfd = res!(pidfd_open(who, PidfdFlags::empty()).map_err(|e| err!(
                    "The hand could not open the launcher {} to take its listener: {}.",
                    pid, e; System, IO)));
                let fd = res!(pidfd_getfd(&pfd, n, PidfdGetfdFlags::empty()).map_err(|e| err!(
                    "The hand could not copy the deletion meter's listener from the launcher \
                    {}: {}.", pid, e; System, IO)));
                return Ok(fd);
            }
        }
        if std::time::Instant::now() > until {
            return Err(err!(
                "The launcher {} did not install the deletion meter within {} s, so the \
                command was not allowed to start.", pid, wait.as_secs(); System, Timeout));
        }
        std::thread::sleep(Duration::from_millis(2));
    }
}

/// Reads a NUL-terminated path from another process's memory.
#[cfg(target_os = "linux")]
fn read_path(pid: u32, addr: u64) -> Option<PathBuf> {
    use std::os::unix::ffi::OsStringExt;
    use std::os::unix::fs::FileExt;
    let f = match std::fs::File::open(fmt!("/proc/{}/mem", pid)) {
        Ok(f)  => f,
        Err(_) => return None,
    };
    let mut out: Vec<u8> = Vec::new();
    let mut at = addr;
    while out.len() < PATH_READ_MAX {
        // Never across a page: the next one may not be mapped.
        let room = (4096 - (at % 4096)) as usize;
        let mut buf = vec![0u8; room.min(PATH_READ_MAX - out.len())];
        let n = match f.read_at(&mut buf, at) {
            Ok(0) | Err(_) => return None,
            Ok(n)          => n,
        };
        if let Some(z) = buf[..n].iter().position(|b| *b == 0) {
            out.extend_from_slice(&buf[..z]);
            return Some(PathBuf::from(std::ffi::OsString::from_vec(out)));
        }
        out.extend_from_slice(&buf[..n]);
        at += n as u64;
    }
    None
}

/// The absolute path a call named, resolved the way the kernel will.
#[cfg(target_os = "linux")]
fn resolve(pid: u32, dirfd: i32, addr: u64) -> Option<PathBuf> {
    let p = match read_path(pid, addr) {
        Some(p) => p,
        None    => return None,
    };
    let full = if p.is_absolute() {
        p
    } else {
        let link = if dirfd == AT_FDCWD {
            fmt!("/proc/{}/cwd", pid)
        } else {
            fmt!("/proc/{}/fd/{}", pid, dirfd)
        };
        match std::fs::read_link(link) {
            Ok(base) => base.join(p),
            Err(_)   => return None,
        }
    };
    let mut clean = PathBuf::new();
    for c in full.components() {
        match c {
            Component::CurDir		=> (),
            Component::ParentDir	=> { clean.pop(); },
            other					=> clean.push(other.as_os_str()),
        }
    }
    // The last name is what the call acts on and is never followed; the directory
    // holding it is, so it is resolved.
    match (clean.parent(), clean.file_name()) {
        (Some(dir), Some(name)) => match dir.canonicalize() {
            Ok(d)  => Some(d.join(name)),
            Err(_) => Some(clean.clone()),
        },
        _ => Some(clean),
    }
}

/// Answers one run's held calls until the last process holding the filter has gone.
///
/// Runs on a thread of its own, because receiving a notification blocks.
///
/// # Arguments
/// * `fd` - The listener, copied out of the launcher.
/// * `w` - The run's marks, budget and trash.
/// * `tx` - Where the held question and the readable refusals go.
/// * `sigtx` - The run's supervisor, told to kill the group when the user says stop.
/// * `answers` - The user's answers to a held question: true to go on.
/// * `tally` - What was counted, for [`Resp::Metered`].
#[cfg(target_os = "linux")]
pub fn watch(
    fd:      std::os::fd::OwnedFd,
    w:       Watch,
    tx:      tokio::sync::mpsc::Sender<Resp>,
    sigtx:   tokio::sync::mpsc::UnboundedSender<Sig>,
    answers: std::sync::mpsc::Receiver<bool>,
    tally:   Arc<Tally>,
) {
    use libseccomp::{
        ScmpNotifReq,
        ScmpNotifResp,
        ScmpNotifRespFlags,
        ScmpSyscall,
    };
    use rustix::event::{
        poll,
        PollFd,
        PollFlags,
        Timespec,
    };
    use std::os::fd::AsRawFd;

    let raw = fd.as_raw_fd();
    let named = |n: &str| ScmpSyscall::from_name(n).ok();
    let (unlink, unlinkat, rmdir) = (named("unlink"), named("unlinkat"), named("rmdir"));
    let (rename, renameat, renameat2) = (named("rename"), named("renameat"), named("renameat2"));

    let mut judge = Judge::new(w.marks.clone(), w.caches.clone(), w.since);
    let mut allowed = false;
    let mut notes: HashSet<PathBuf> = HashSet::new();
    let mut sample: Vec<String> = Vec::new();
    let tick = Timespec { tv_sec: 0, tv_nsec: 250_000_000 };

    let answer = |id: u64, errno: i32| {
        let r = if errno == 0 {
            ScmpNotifResp::new_continue(id, ScmpNotifRespFlags::empty())
        } else {
            ScmpNotifResp::new_error(id, -errno, ScmpNotifRespFlags::empty())
        };
        // The caller may have died meanwhile; nothing is owed to it.
        let _ = r.respond(raw);
    };

    loop {
        let mut fds = [PollFd::new(&fd, PollFlags::IN)];
        match poll(&mut fds, Some(&tick)) {
            Ok(0)  => continue,
            Ok(_)  => (),
            Err(_) => continue,
        }
        let rev = fds[0].revents();
        if rev.contains(PollFlags::HUP) && !rev.contains(PollFlags::IN) {
            break; // Nothing holds the filter any more.
        }
        let req = match ScmpNotifReq::receive(raw) {
            Ok(r)  => r,
            Err(_) => continue, // The caller died between the poll and the receive.
        };
        let sc = Some(req.data.syscall);
        let a = req.data.args;
        let pid = req.pid;
        let path_at = |dfd: u64, addr: u64| resolve(pid, dfd as u32 as i32, addr);

        let verdict = if sc == unlink || sc == rmdir {
            path_at(AT_FDCWD as u32 as u64, a[0]).map(|p| judge.remove(&p, sc == rmdir))
        } else if sc == unlinkat {
            path_at(a[0], a[1]).map(|p| judge.remove(&p, a[2] & AT_REMOVEDIR != 0))
        } else if sc == rename {
            match (path_at(AT_FDCWD as u32 as u64, a[0]), path_at(AT_FDCWD as u32 as u64, a[1])) {
                (Some(f), Some(t)) => Some(judge.rename(&f, &t, 0)),
                _ => None,
            }
        } else if sc == renameat || sc == renameat2 {
            // Only `renameat2` carries flags; `renameat`'s fifth register is whatever was left there.
            let flags = if sc == renameat2 { a[4] } else { 0 };
            match (path_at(a[0], a[1]), path_at(a[2], a[3])) {
                (Some(f), Some(t)) => Some(judge.rename(&f, &t, flags)),
                _ => None,
            }
        } else {
            Some(Verdict::Go)
        };

        // The path was read from memory the caller could have changed; a request the
        // kernel no longer knows is one whose answer means nothing.
        if libseccomp::notify_id_valid(raw, req.id).is_err() {
            continue;
        }

        let verdict = match verdict {
            Some(v) => v,
            // Unreadable: refused rather than guessed at.
            None    => { answer(req.id, libc_eperm()); continue; },
        };

        match verdict {
            Verdict::Go   => answer(req.id, 0),
            Verdict::Xdev => answer(req.id, libc_exdev()),
            Verdict::Root(p) => {
                // Said before the answer, so it reaches the page before the command's end.
                if notes.len() < NOTES_MAX && notes.insert(p.clone()) {
                    let _ = tx.blocking_send(Resp::Error {
                        id:      Some(w.id.clone()),
                        message: fmt!(
                            "The hand refused to remove or move {}: it is a root this command \
                            was given (a Diamond's folder, or the folder the hand was granted), \
                            or it holds one, and a root cannot be removed or moved away by a \
                            command. Remove what is inside it instead, if that is what was \
                            meant.", p.display()),
                    });
                }
                answer(req.id, libc_eperm());
            },
            Verdict::Count(victim, mark) => {
                if tally.stopped.load(Ordering::Relaxed) {
                    answer(req.id, libc_eperm());
                    continue;
                }
                let spent = tally.counted.load(Ordering::Relaxed);
                if spent >= w.budget && !allowed {
                    // Held: the call is not answered until the user says.
                    let _ = tx.blocking_send(Resp::Held {
                        id:      w.id.clone(),
                        counted: spent,
                        sample:  sample.clone(),
                        mark:    fmt!("{}", mark.display()),
                        since_ms: w.since_ms,
                    });
                    let go = matches!(
                        answers.recv_timeout(Duration::from_millis(HOLD_MS)), Ok(true));
                    if go {
                        allowed = true;
                    } else {
                        tally.stopped.store(true, Ordering::Relaxed);
                        let _ = tx.blocking_send(Resp::Error {
                            id:      Some(w.id.clone()),
                            message: fmt!(
                                "The hand stopped this command. It had removed {} files in {} \
                                that existed before this turn -- the most a turn may remove \
                                without asking -- and the user did not let it go on. Those \
                                files are in the hand's trash and the user can put them back. \
                                Do not try to remove them another way.",
                                spent, mark.display()),
                        });
                        answer(req.id, libc_eperm());
                        let _ = sigtx.send(Sig::Kill);
                        continue;
                    }
                }
                match keep(&w.trash, w.since_ms, &victim) {
                    Ok(()) => {
                        tally.counted.fetch_add(1, Ordering::Relaxed);
                        if sample.len() < SAMPLE_MAX {
                            sample.push(fmt!("{}", victim.display()));
                        }
                        answer(req.id, 0);
                    },
                    Err(e) => {
                        // Said, like a root's refusal: a bare "Operation not permitted" names
                        // no cause, and a model reading one tries the removal another way.
                        if notes.len() < NOTES_MAX && notes.insert(victim.clone()) {
                            let _ = tx.blocking_send(Resp::Error {
                                id:      Some(w.id.clone()),
                                message: fmt!(
                                    "The hand refused to remove {}, because it must keep a file \
                                    before a command removes it and could not: {}.",
                                    victim.display(), e.msgs().join(" ")),
                            });
                        }
                        answer(req.id, libc_eperm());
                    },
                }
            },
        }
    }
}

#[cfg(target_os = "linux")]
fn libc_eperm() -> i32 { rustix::io::Errno::PERM.raw_os_error() }

#[cfg(target_os = "linux")]
fn libc_exdev() -> i32 { rustix::io::Errno::XDEV.raw_os_error() }

