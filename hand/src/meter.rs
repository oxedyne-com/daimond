//! The deletion meter: every removal a fenced command makes, held in the kernel while the
//! hand decides whether it counts.
//!
//! Built 2026-09-23 from `daimond_hand_delete_fence_design_20260923.md`, section 4.2 and
//! 4.3, after a daimon's command emptied a Diamond on 2026-09-22.  Landlock cannot refuse
//! removal inside a mark without breaking git and every atomic save, so the fence alone
//! lets a command empty a mark; this module is the part that does not.
//!
//! The launcher installs a second seccomp filter that answers `SCMP_ACT_NOTIFY` for
//! `unlink`, `unlinkat`, `rmdir`, `rename`, `renameat` and `renameat2`.  The hand takes the
//! listener with `pidfd_getfd` before the command exists, and [`watch`] answers each call:
//! let it through, refuse it, or -- once the turn's [`BUDGET`] of pre-existing files is
//! spent -- leave it unanswered, so the command sits blocked in the kernel until the user
//! says whether it may go on.  Every counted file is hard-linked into a trash outside the
//! fence first, so what does go can be put back.  Where the mark is on another filesystem the
//! file is copied instead, up to [`COPY_MAX`], and a larger one is not removed at all (audit F6).
//!
//! The filter needs the `libseccomp` crate, a safe binding over the system's
//! `libseccomp.so.2`, which the owner approved on 2026-09-23: `seccompiler` has no notify
//! action, rustix does not wrap seccomp, and the hand writes no `unsafe`.
//!
//! A rename onto a file that was there before the turn is counted too, as a removal of the
//! file it replaces, and that file is kept first (audit F3, 2026-09-23).
//!
//! Holes, stated rather than left to be found, and both Phase 2 of the design: a file
//! emptied or overwritten in place (`O_TRUNC`, `truncate`, `dd`, a write over it) loses its
//! old bytes through no call this filter holds, so it is neither counted nor kept; and the
//! path is read from the caller's memory, so a second thread rewriting it between the check
//! and the kernel's own read could make a counted removal look free.  The COUNT of calls
//! cannot be raced; only the classification can.

