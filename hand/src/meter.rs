    /// **A file the trash cannot link is copied only while it is small, and never through a
    /// link (audit F6).**
    ///
    /// `copy_kept` is what `keep` falls back to when the hard link fails -- a mark on another
    /// filesystem -- and it is called directly here, because a second filesystem is not
    /// something a unit test can count on having.  `dev/verify_handdelete.mjs` drives the real
    /// fallback, through the kernel, where one exists.
    #[test]
    fn a_file_the_trash_cannot_link_is_copied_only_while_small() -> Outcome<()> {
        let base = res!(tree("copy-kept"));
        let trash = base.join("trash");
        res!(std::fs::create_dir_all(&trash));
        let small = base.join("small.txt");
        let big = base.join("big.bin");
        res!(std::fs::write(&small, "kept"));
        res!(std::fs::write(&big, vec![0u8; (COPY_MAX + 1) as usize]));
        res!(copy_kept(&small, &trash.join("small.txt")));
        assert_eq!("kept", res!(std::fs::read_to_string(trash.join("small.txt"))));
        // Over the ceiling: refused, saying why, and nothing half-copied left behind.
        match copy_kept(&big, &trash.join("big.bin")) {
            Ok(()) => panic!("a file over COPY_MAX was copied"),
            Err(e) => assert!(e.msgs().join(" ").contains("copies nothing over"), "{}", e),
        }
        assert!(std::fs::symlink_metadata(trash.join("big.bin")).is_err(),
            "a refused copy left a file in the trash");
        // A link is kept as the link it is, and not as the large file it points at.
        let link = base.join("link");
        res!(std::os::unix::fs::symlink(&big, &link));
        res!(copy_kept(&link, &trash.join("link")));
        let kept = res!(std::fs::symlink_metadata(trash.join("link")));
        assert!(kept.file_type().is_symlink(), "a link was kept as what it points at");
        assert_eq!(big, res!(std::fs::read_link(trash.join("link"))));
        Ok(())
    }

    /// **A kept file comes back, and one whose place is taken again stays kept.**
    #[test]
