/// Pre-existing files a turn may remove before the user is asked.
pub const BUDGET: u32 = 64;

/// How long a held command waits for an answer before it is stopped.
pub const HOLD_MS: u64 = 120_000;

/// How long the trash keeps a turn's files.
pub const TRASH_KEEP: Duration = Duration::from_secs(7 * 24 * 3600);

/// Where the trash lives, when the operator says so.
pub const TRASH_DIR_VAR: &str = "DAIMOND_HAND_TRASH_DIR";

/// The calls the meter holds.  A name this architecture lacks is skipped.
pub const METERED: &[&str] = &["unlink", "unlinkat", "rmdir", "rename", "renameat", "renameat2"];

/// Directories whose contents are regenerated by a tool and so are not counted.
const CACHE_NAMES: &[&str] = &["node_modules", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"];

/// What `/proc/<pid>/fd/<n>` reads as for a seccomp listener.
const LISTENER_LINK: &str = "anon_inode:seccomp notify";

const AT_FDCWD:     i32 = -100;
const AT_REMOVEDIR: u64 = 0x200;
const RENAME_NOREPLACE: u64 = 1;	// renameat2: fail rather than replace
const RENAME_EXCHANGE:  u64 = 2;	// renameat2: swap the two, losing neither
const PATH_READ_MAX: usize = 4096;
const NOTES_MAX:     usize = 8;	// readable refusals sent per run, so a loop cannot flood the page
const SAMPLE_MAX:    usize = 5;

// Copying in place of a link
//
// A counted file is hard-linked into the trash, which costs nothing.  Where the mark is on a
// different filesystem from the trash the link fails, and the only way to keep the file is to
// copy it -- which costs its whole size, in trash space and in time spent with the command
// blocked in the kernel.  So only a file this small is copied: the page's own
// `VERSION_FILE_MAX`, which the design named for exactly this (§4.3, audit F6).
pub const COPY_MAX: u64 = 512 * 1024;

/// What one run's meter found, read by the supervisor when the run ends.
#[derive(Debug, Default)]
pub struct Tally {
    pub counted: AtomicU32,
    pub stopped: AtomicBool,
}

/// What one run's meter is told.
#[derive(Clone, Debug)]
pub struct Watch {
    pub id:       String,
    pub marks:    Vec<PathBuf>,	// canonical roots whose pre-existing files are counted
    pub caches:   Vec<PathBuf>,	// canonical toolchain caches, free wherever a mark holds one
    pub budget:   u32,			// counted removals left this turn
    pub since:    SystemTime,	// the turn's start: a file born after it is free
    pub since_ms: u64,			// the same, as the page named it, which keys the trash
    pub trash:    PathBuf,		// the trash root, outside every fence
}

impl Watch {

    /// The turn start as a time, from the page's milliseconds.
    pub fn since_of(ms: u64) -> SystemTime {
        UNIX_EPOCH + Duration::from_millis(ms)
    }

    /// Now, in the page's milliseconds.
    pub fn now_ms() -> u64 {
        match SystemTime::now().duration_since(UNIX_EPOCH) {
            Ok(d)  => d.as_millis() as u64,
            Err(_) => 0,
        }
    }
}

/// Where the trash lives: beside the journal and the scratch, and never inside a fence.
pub fn trash_root() -> Outcome<PathBuf> {
    if let Ok(v) = std::env::var(TRASH_DIR_VAR) {
        if !v.is_empty() {
            return Ok(PathBuf::from(v));
        }
    }
    if let Ok(x) = std::env::var("XDG_DATA_HOME") {
        if !x.is_empty() {
            return Ok(Path::new(&x).join("daimond/hand/trash"));
        }
    }
    match std::env::var("HOME") {
        Ok(h) if !h.is_empty() => Ok(Path::new(&h).join(".local/share/daimond/hand/trash")),
        _ => Err(err!(
            "Neither XDG_DATA_HOME nor HOME is set, so the hand cannot say where removed files \
            are kept. Set {}.", TRASH_DIR_VAR;
            Missing, Configuration, Path)),
    }
}

/// Removes turns older than [`TRASH_KEEP`].  Best effort: a failure leaves a turn for the
/// next sweep.
pub fn sweep(root: &Path) {
    let rd = match std::fs::read_dir(root) {
        Ok(rd) => rd,
        Err(_) => return,
    };
    let now = SystemTime::now();
    for e in rd.flatten() {
        let old = match e.metadata().and_then(|m| m.modified()) {
            Ok(t)  => now.duration_since(t).map(|d| d > TRASH_KEEP).unwrap_or(false),
            Err(_) => false,
        };
        if old {
            let _ = std::fs::remove_dir_all(e.path());
        }
    }
}

/// Puts back every file the meter took during the turn `since_ms`.
///
/// A file whose original path is occupied again is left in the trash and counted as
/// skipped: something now stands there, and overwriting it would be a second loss.
///
/// # Returns
/// `(restored, skipped)`.
pub fn restore(root: &Path, since_ms: u64) -> Outcome<(u32, u32)> {
    let turn = root.join(fmt!("{}", since_ms));
    if !turn.is_dir() {
        return Err(err!(
            "There is nothing in the trash for the turn that began at {} ms: either nothing was \
            removed then, or it has been more than seven days.", since_ms;
            NotFound, Path));
    }
    // Layer 0 first: a path taken twice in one turn is put back as it was the first time.
    let mut layers: Vec<(u64, PathBuf)> = Vec::new();
    for e in res!(std::fs::read_dir(&turn)).flatten() {
        if let Ok(k) = e.file_name().to_string_lossy().parse::<u64>() {
            layers.push((k, e.path()));
        }
    }
    layers.sort();
    let mut n = (0u32, 0u32);
    for (_, layer) in &layers {
        res!(put_back(layer, layer, &mut n));
    }
    let _ = remove_empty(&turn);
    Ok(n)
}

fn put_back(turn: &Path, dir: &Path, n: &mut (u32, u32)) -> Outcome<()> {
    let rd = res!(std::fs::read_dir(dir));
    for e in rd {
        let e = res!(e);
        let p = e.path();
        let ft = res!(e.file_type());
        if ft.is_dir() {
            res!(put_back(turn, &p, n));
            continue;
        }
        let rel = match p.strip_prefix(turn) {
            Ok(r)  => r,
            Err(_) => continue,
        };
        // Only plain names: the trash is written by this module alone, and a path that
        // is anything else was not.
        if rel.components().any(|c| !matches!(c, Component::Normal(_))) {
            n.1 += 1;
            continue;
        }
        let orig = Path::new("/").join(rel);
        if std::fs::symlink_metadata(&orig).is_ok() {
            n.1 += 1;
            continue;
        }
        if let Some(parent) = orig.parent() {
            res!(std::fs::create_dir_all(parent));
        }
        let moved = match std::fs::rename(&p, &orig) {
            Ok(()) => true,
            Err(_) => std::fs::copy(&p, &orig).is_ok() && std::fs::remove_file(&p).is_ok(),
        };
        if moved { n.0 += 1; } else { n.1 += 1; }
    }
    Ok(())
}

fn remove_empty(dir: &Path) -> bool {
    let rd = match std::fs::read_dir(dir) {
        Ok(rd) => rd,
        Err(_) => return false,
    };
    let mut empty = true;
    for e in rd.flatten() {
        let p = e.path();
        if !(p.is_dir() && remove_empty(&p)) {
            empty = false;
        }
    }
    empty && std::fs::remove_dir(dir).is_ok()
}

